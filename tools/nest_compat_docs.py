"""Write docs/nests/COMPATIBILITY*.md from a WOOF-NAM suite cycle and NOAA's NAM nest files.

For each nest (conusnest, alaskanest, hawaiinest, priconest, firewxnest) with a WOOF-NAM file and a NOAA file of the
same forecast hour, it runs tools/grib2_compat_nest.py (record by record: number, inventory text, GRIB2 keys, grid,
precision) and compares the .idx of every other hour both sides have (the record list and its time windows, line by
line without the date: ours should be NOAA's lines in NOAA's order with some left out). Every number in the pages comes from that run; nothing is typed by hand.

    python -I tools/nest_compat_docs.py --noaa DIR --ours DIR [--hour 01] [--out docs/nests] [--json OUT.json]

DIR holds `nam.tHHz.<nest>.hiresfFF.tm00.grib2` (+ .idx) for NOAA and `woof-nam.tHHz.<nest>.hiresfFF.tm00.grib2`
(+ .idx) for ours, flat or in subfolders.
"""
from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import grib2_compat_nest as cn  # noqa: E402

NESTS = {
    "conusnest": ("CONUS", "60"),
    "alaskanest": ("Alaska", "60"),
    "hawaiinest": ("Hawaii", "60"),
    "priconest": ("Puerto Rico", "60"),
    "firewxnest": ("Fire weather", "36"),
}
PAT = re.compile(r"^(?P<pre>nam|woof-nam)\.t(?P<HH>\d\d)z\.(?P<nest>[a-z]+nest)\.hiresf(?P<FF>\d\d)\.tm00\.grib2$")


def files(root: Path, prefix: str) -> dict:
    """(nest, FF) -> (path, HH, has_grib) for every hiresf file or .idx under root."""
    out = {}
    for p in root.rglob("*hiresf*"):
        name = p.name[:-4] if p.name.endswith(".idx") else p.name
        m = PAT.match(name)
        if not m or m["pre"] != prefix or m["nest"] not in NESTS:
            continue
        key = (m["nest"], m["FF"])
        g = p.with_name(name)
        prev = out.get(key)
        has = g.exists()
        if prev is None or (has and not prev[2]):
            out[key] = (g, m["HH"], has)
    return out


def idx_lines(path: Path) -> list[tuple[str, str]]:
    p = Path(str(path) + ".idx")
    if not p.exists():
        return []
    rows = []
    for line in p.read_text().splitlines():
        parts = line.split(":")
        if len(parts) >= 4:
            rows.append((parts[0], ":".join(parts[3:])))
    return rows


def idx_compare(a: Path, b: Path) -> dict:
    """NOAA's .idx against ours, text after the date: are ours NOAA's lines, in NOAA's order, with some left out?"""
    ra, rb = idx_lines(a), idx_lines(b)
    ta, tb = [t for _, t in ra], [t for _, t in rb]
    left, j = [], 0
    for t in ta:                                       # ours as an ordered subsequence of NOAA's
        if j < len(tb) and tb[j] == t:
            j += 1
        else:
            left.append(t)
    subseq = j == len(tb)
    # each of our lines against NOAA's line with the same text (the n-th occurrence of that text): same number?
    noaa_num, seen, first = {}, {}, None
    for n_, t in ra:
        k = (t, seen.get(t, 0))
        seen[t] = k[1] + 1
        noaa_num[k] = n_
    seen = {}
    for i, (n_, t) in enumerate(rb):
        k = (t, seen.get(t, 0))
        seen[t] = k[1] + 1
        if k in noaa_num and noaa_num[k] != n_:
            first = (i, noaa_num[k], n_, t)
            break
    return {"noaa_lines": len(ra), "our_lines": len(rb), "identical": bool(ra) and ra == rb,
            "subsequence": bool(rb) and subseq, "left_out": len(left) if subseq else None,
            "left_out_records": sorted({":".join(t.split(":")[:2]) for t in left}) if subseq else [],
            "numbers_same_for_first": len(rb) if first is None else first[0],
            "first_number_difference": "" if first is None else
            f"{first[3].split(':')[0]} {first[3].split(':')[1]}: NOAA {first[1]} / ours {first[2]}",
            "first_left_out": left[0] if left else "",
            "first_left_out_number": next((n_ for n_, t in ra if left and t == left[0]), "")}


def page(nest: str, hour: str, res: dict, idxres: dict, head, rows, summary) -> str:
    title, length = NESTS[nest]
    s = res
    lines = [
        f"# {title} nest: `woof-nam.tHHz.{nest}.hiresfFF.tm00.grib2` against NOAA's "
        f"`nam.tHHz.{nest}.hiresfFF.tm00.grib2`",
        "",
        f"Generated by `tools/nest_compat_docs.py`: WOOF-NAM's {s['ours_cycle']} file against NOAA's {s['noaa_cycle']} "
        f"file of 2026-11-03 (NOAA's last complete NAM forecast). Hour {hour} is compared record by record; every other "
        "hour both sides have is compared by its `.idx`. [COMPATIBILITY.md](COMPATIBILITY.md) explains the columns.",
        "",
        "## Summary",
        "",
    ]
    lines += [f"- {x}" for x in summary if not x.startswith("NOAA:") and not x.startswith("ours:")]
    lines += [f"- NOAA's file: {s['noaa_fields']} fields in {s['noaa_messages']} messages; ours: {s['our_fields']} "
              f"fields in {s['our_messages']} messages."]
    if idxres:
        lines += ["", "## Record list at every hour compared (from the .idx, date removed)", "",
                  "| hour | NOAA lines | our lines | ours = NOAA's lines in NOAA's order, some left out | left out | "
                  "record numbers as NOAA's for the first | first number that differs |",
                  "|---|---|---|---|---|---|---|"]
        for ff, r in sorted(idxres.items()):
            lines.append(f"| f{ff} | {r['noaa_lines']} | {r['our_lines']} | {'yes' if r['subsequence'] else 'no'} | "
                         f"{r['left_out'] if r['left_out'] is not None else '-'} | {r['numbers_same_for_first']} | "
                         f"{r['first_number_difference'] or '-'} |")
    lines += ["", f"## Every record of NOAA's hour-{hour} file, in NOAA's order", "",
              "| " + " | ".join(head) + " |", "|" + "---|" * len(head)]
    lines += ["| " + " | ".join(str(c).replace("|", "/") for c in x) + " |" for x in rows]
    return "\n".join(lines) + "\n"


DRT = {3: "complex packing with spatial differencing (template 5.3)", 40: "JPEG 2000 (template 5.40)",
       0: "simple packing (template 5.0)", 2: "complex packing (template 5.2)"}


def _group(names: list[str]) -> str:
    """'CICE 100 mb', 'CICE 125 mb', ... -> 'CICE (41 levels)'; others as they are."""
    by = {}
    for n in names:
        var, _, lev = n.partition(" ")
        by.setdefault(var, []).append(lev)
    out = []
    for var, levs in sorted(by.items()):
        out.append(f"{var} ({len(levs)} levels)" if len(levs) > 3 else
                   "; ".join(f"{var} {lv}" for lv in sorted(levs)))
    return "; ".join(out)


def _bm(v: list) -> str:
    return "some" if v == [0, 1] else ("every" if v == [1] else "no")


def overview(results: dict, hour: str, made_by: str = "") -> str:
    """docs/nests/COMPATIBILITY.md: the reading guide; every claim in it is conditioned on the measured results."""
    rs = list(results.values())

    def T(r):
        return NESTS[r["nest"]][0]
    all_grid = all(r["grid_identical"] for r in rs)
    idx_all = [v for r in rs for v in r["idx"].values()]
    all_subseq = bool(idx_all) and all(v["subsequence"] for v in idx_all)
    all_differ0 = all(r["differ"] == 0 for r in rs)
    all_order = all(r["in_order"] for r in rs)
    all_bitmap = all(r["our_bitmap"] == r["noaa_bitmap"] for r in rs)
    procs = sorted({p for r in rs for p in r["our_process"]})
    hours = sorted({ff for r in rs for ff in r["idx"]})
    L = ["# WOOF-NAM nest GRIB2 files and NOAA's NAM nest files", "",
         "NOAA's NAM ran five nests inside its 12 km parent and wrote one GRIB2 file per nest and forecast hour, "
         "`nam.tHHz.<nest>.hiresfFF.tm00.grib2`. WOOF-NAM writes the same files for the same nests, named "
         "`woof-nam.tHHz.<nest>.hiresfFF.tm00.grib2`, each with a `.idx` beside it (what `wgrib2 -s` prints). This "
         "page says, record by record, how close ours are to NOAA's, and what a site or converter that read NOAA's "
         "files changes to read ours. The 12 km files are covered by [../COMPATIBILITY.md](../COMPATIBILITY.md).",
         "", "| nest | `<nest>` | forecast hours | output grid (NOAA's) |", "|---|---|---|---|",
         "| CONUS 3 km | `conusnest` | 00-60 | Lambert conformal 1799 x 1059 at 3 km (the HRRR CONUS grid) |",
         "| Alaska 3 km | `alaskanest` | 00-60 | polar stereographic 1649 x 1105 at 2.976 km |",
         "| Hawaii 3 km | `hawaiinest` | 00-60 | Mercator 321 x 225 at 2.5 km |",
         "| Puerto Rico 3 km | `priconest` | 00-60 | Mercator 544 x 310 at 2.5 km |",
         "| Fire weather 1.5 km | `firewxnest` | 00-36 | Lambert conformal at 1.27 km: the box around the nest on "
         "NCEP's 1.27 km master grid, so it moves with the nest's centre. `woof-nam.tHHz.firewxnest_center_latlon` "
         "gives the centre of each cycle. |",
         "", "## How we checked", "",
         "`tools/nest_compat_docs.py` compares WOOF-NAM nest files with NOAA's files from its last complete NAM "
         f"forecast, 2026-11-03 06Z. {made_by}For each nest it decodes hour {hour} of both files in full with ecCodes "
         "and goes through NOAA's records in NOAA's order (`tools/grib2_compat_nest.py`). For each record it checks "
         "whether ours has it, its inventory text, every key a decoder selects on (name, level, time range, "
         "statistic, units, the GRIB2 codes, bitmap), its record number (wgrib2's `N`, or `N.1`/`N.2` for the two "
         "winds of one message), its packing template and the grid section. "
         f"Then it compares the `.idx` of every hour both sides have ({', '.join('f' + h for h in hours)}), line by "
         "line without the date. That checks the record list and its time windows at f00 and at the later hours. "
         "Values are not compared here. Every number on these pages comes from that run.",
         "", "## Results", "",
         f"| nest | NOAA's records (f{hour}) | ours | ours with NOAA's text and keys | NOAA's not in ours | "
         "grid section | packing | record list at every hour |", "|---|---|---|---|---|---|---|---|"]
    for r in rs:
        lo = sorted({v["left_out"] for v in r["idx"].values() if v["left_out"] is not None})
        lst = ("NOAA's, in NOAA's order, with " + "/".join(map(str, lo)) + " left out"
               if r["idx"] and all(v["subsequence"] for v in r["idx"].values()) else "differs (see the nest's page)")
        pk = ("as NOAA's" if r["our_packing"] == r["noaa_packing"] else
              f"5.{'/'.join(map(str, r['our_packing']))} (NOAA's 5.{'/'.join(map(str, r['noaa_packing']))})")
        L.append(f"| {T(r)} | {r['records']} | {r['our_fields']} | {r['same']} | {r['missing']} | "
                 f"{'identical' if r['grid_identical'] else 'differs'} | {pk} | {lst} |")
    L += ["", "Each nest's page lists every record: "
          + ", ".join(f"[{T(r)}](COMPATIBILITY-{r['nest']}.md)" for r in rs) + ".", "",
          "## What works unchanged", ""]
    if all_grid:
        L.append("- **The grids.** Each file's grid section (GRIB2 section 3) is identical to NOAA's for the same nest "
                 "(for fire weather, for the same centre). Every reader gives the same latitude and longitude at every "
                 "point.")
    if all_order:
        clean = [T(r) for r in rs if r["differ"] == 0]
        L.append("- **The records we write.** They come in NOAA's order, each with NOAA's inventory text and every "
                 "GRIB2 key a decoder selects on" + ("" if all_differ0 else
                 f" ({', '.join(clean)}; the exception is listed under \"NOAA's records that are not in our files, "
                 "or differ\")") + ". So `wgrib2 -match` patterns, pygrib `select` and cfgrib `filter_by_keys` "
                 "written for NOAA's files find the same records.")
    if all_subseq:
        L.append(f"- **The record lists, at every hour.** At {', '.join('f' + h for h in hours)} each `.idx` is NOAA's "
                 "`.idx` with the same records left out and nothing else changed: same lines, same order, same time "
                 "text. f00 has NOAA's analysis-time list; the later hours have NOAA's forecast list.")
        fw = "firewxnest" in results
        L.append("- **The time windows.** They are NOAA's: hourly maxima and minima cover the last hour (F-1 to F); "
                 "accumulations and averages run in NOAA's 3-hour buckets (0-1, 0-2, 0-3, 3-4, ...)"
                 + ("; in the fire-weather nest, which NCEP emptied every hour, over the last hour (0-1, 1-2, "
                    "2-3, ...)" if fw else "") + "; at f00 they are NOAA's 0-0 windows.")
    L.append("- **U and V.** Each U/V pair (and USTM/VSTM) is one two-field message, as in NOAA's files "
             "(`N.1`/`N.2` in the `.idx`), and the winds are grid-relative, as NOAA's.")
    if all_bitmap:
        L.append("- **Missing values.** Points of the output grid outside the nest are marked missing with a bitmap, "
                 "as in NOAA's files; readers give them as NaN.")
    else:
        for r in rs:
            if r["our_bitmap"] != r["noaa_bitmap"]:
                L.append(f"- **Missing values, {T(r)}:** NOAA's file has a bitmap on {_bm(r['noaa_bitmap'])} record, "
                         f"ours on {_bm(r['our_bitmap'])} record. The nest's page lists the records.")
    L += ["", "## What a site must change", "",
          "- **The file name** starts with `woof-nam.` where NOAA's starts with `nam.`."]
    if procs and procs != [84]:
        L.append(f"- **The generating process number** is {', '.join(map(str, procs))} (WOOF-NAM) where NOAA's is 84 "
                 "(NAM). Only a script that filters on it changes.")
    renum = [r for r in rs if r["renumbered"]]
    if renum and idx_all:
        firsts = sorted({" ".join(v["first_left_out"].split(":")[:2]) for v in idx_all if v.get("first_left_out")})
        L.append("- **Record numbers.** Our files leave out the records we do not write yet (below), and a record "
                 "number counts the records in the file. So after the first record left out ("
                 f"{' / '.join(firsts)}: NOAA's record "
                 f"{' or '.join(sorted({str(v['first_left_out_number']) for v in idx_all if v.get('first_left_out_number')}, key=int))}) our numbers run "
                 "behind NOAA's. "
                 "Select records by their inventory text (variable, level and time, as `wgrib2 -match` does), not by "
                 "NOAA's record number. Byte ranges come from our own `.idx`, as for any GRIB2 file.")
    packs = [r for r in rs if r["our_packing"] != r["noaa_packing"]]
    if packs:
        L.append("- **Packing.** " + "; ".join(
            f"{T(r)}: {', '.join(DRT.get(x, str(x)) for x in r['our_packing'])} where NOAA's is "
            f"{', '.join(DRT.get(x, str(x)) for x in r['noaa_packing'])}" for r in packs)
            + ". A pipeline that fixes the codec per file family sees one template per nest, the same in every hour "
              "and cycle.")
    same_pack = [r for r in rs if r["our_packing"] == r["noaa_packing"]]
    if same_pack:
        L.append("- **Packing that is unchanged:** " + "; ".join(
            f"{T(r)} {', '.join(DRT.get(x, str(x)) for x in r['our_packing'])}" for r in same_pack) + ", as NOAA's.")
    miss = [r for r in rs if r["missing"]]
    if miss:
        sets = {tuple(sorted({m.split(" ", 1)[1].split(",")[0] for m in r["missing_records"]})) for r in miss}
        L += ["", "## NOAA's records that are not in our files, or differ", ""]
        if len(sets) == 1:
            names = list(next(iter(sets)))
            L.append(f"The same {len(names)} records are left out of every nest ("
                     + ", ".join(f"{T(r)} {r['missing']} of {r['records']}" for r in miss) + ")"
                     + (", at every hour compared" if all_subseq else "") + ": " + _group(names)
                     + ". A record we do not write is left out, never written as zeros or under another record's "
                       "name.")
        else:
            for r in miss:
                names = sorted({m.split(" ", 1)[1].split(",")[0] for m in r["missing_records"]})
                L.append(f"- **{T(r)}:** {r['missing']} of NOAA's {r['records']}: " + _group(names) + ".")
    for r in [r for r in rs if r["extra"]]:
        L.append(f"- **{T(r)}:** {len(r['extra'])} records of ours are not in NOAA's file: {', '.join(r['extra'])}.")
    for r in [r for r in rs if r["differ"]]:
        notes = [x.split(": ", 1) for x in r["differ_records"]]
        only_bm = all(any(k.startswith("bitmap NOAA 1 / ours 0") for k in n.split("; ")) and
                      all(k.startswith(("bitmap", "step")) for k in n.split("; ")) for _, n in notes)
        names = sorted({lab.split(" ", 1)[1].split(",")[0] for lab, _ in notes})
        if only_bm and all("above mean sea level" in n for n in names):
            L.append(f"- **{T(r)}:** {r['differ']} records, the flight-level TMP, UGRD and VGRD, have a bitmap in "
                     "NOAA's file and none in ours: NOAA's whole Hawaii grid lies inside the nest, so its only missing "
                     "points are those below the ground (next bullet).")
        else:
            L.append(f"- **{T(r)}:** {r['differ']} records are present with a key that differs; the nest's page gives "
                     "each.")
    fl = [r for r in rs if r.get("flight_level_below_ground") == "noaa-only"]
    if fl:
        L.append("- **Flight levels below the ground.** TMP, UGRD and VGRD at 305-3658 m above mean sea level: NOAA's "
                 "files mark the points where that level lies below the ground missing; ours carry a value there ("
                 "points missing at 305 m beyond those missing at 2 m: "
                 + "; ".join(f"{T(r)} NOAA {r['fl_missing'][0] - r['fl_missing'][2]:,}, ours "
                             f"{r['fl_missing'][1] - r['fl_missing'][3]:,}" for r in fl)
                 + "). Read these records above the ground only, or mask them with the surface height.")
    L += ["", "## Precision", "",
          "NOAA's nests chose each record's decimal and binary scale per file from the data: the same record "
          "carries different scales in NOAA's CONUS and Alaska files of the same hour. So precision is listed apart "
          "from the keys, as our packing step (2^E / 10^D) against NOAA's in the file compared: "
          + "; ".join(f"{T(r)}: {r['precision'].split(': ', 1)[-1]}" for r in rs) + ". Each nest's page names the "
          "records where ours is coarser."]
    return "\n".join(L) + "\n"


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--noaa", type=Path, required=True)
    ap.add_argument("--ours", type=Path, required=True)
    ap.add_argument("--hour", default="01")
    ap.add_argument("--out", type=Path)
    ap.add_argument("--json", type=Path)
    ap.add_argument("--made-by", default="", help="one sentence on the WOOF-NAM runs the files came from")
    a = ap.parse_args(argv)
    noaa, ours = files(a.noaa, "nam"), files(a.ours, "woof-nam")
    results = {}
    for nest in NESTS:
        n, o = noaa.get((nest, a.hour)), ours.get((nest, a.hour))
        if not n or not o or not n[2] or not o[2]:
            print(f"{nest}: no full hour-{a.hour} pair (NOAA {'yes' if n and n[2] else 'no'}, "
                  f"ours {'yes' if o and o[2] else 'no'}); skipped")
            continue
        head, rows, summary = cn.compare(n[0], o[0], plain=True)
        counts = {k: sum(1 for r in rows if r[2] == "yes" and r[3] == k) for k in ("yes", "no")}
        renum = sum(1 for r in rows if r[2] == "yes" and r[4] != "yes")
        missing = [r for r in rows if r[2] == "no"]
        idxres = {}
        for (nn, ff), (np_, _, _) in sorted(noaa.items()):
            if nn == nest and (nest, ff) in ours:
                idxres[ff] = idx_compare(np_, ours[(nest, ff)][0])
        ref, mine = cn.fields(n[0]), cn.fields(o[0])
        res = {
            "nest": nest, "noaa_file": n[0].name, "our_file": o[0].name, "noaa_cycle": f"t{n[1]}z", "ours_cycle": f"t{o[1]}z",
            "noaa_fields": len(ref), "noaa_messages": ref[-1]["messages"], "our_fields": len(mine),
            "our_messages": mine[-1]["messages"] if mine else 0, "records": len(rows),
            "same": counts["yes"], "differ": counts["no"], "missing": len(missing), "renumbered": renum,
            "in_order": any(x.endswith("NOAA's order: yes") for x in summary),
            "coarser": [f"{r[0]} {r[1]}: {r[7]}" for r in rows if r[2] == "yes" and r[6] == "coarser"],
            "missing_records": [f"{r[0]} {r[1]}" for r in missing],
            "grid_identical": any(x == "grid section: identical" for x in summary),
            "precision": next((x for x in summary if x.startswith("precision")), ""),
            "summary": summary, "idx": idxres,
            "noaa_packing": sorted({d["dataRepresentationTemplateNumber"] for d in ref}),
            "our_packing": sorted({d["dataRepresentationTemplateNumber"] for d in mine}),
            "noaa_process": sorted({d["generatingProcessIdentifier"] for d in ref}),
            "our_process": sorted({d["generatingProcessIdentifier"] for d in mine}),
            "noaa_bitmap": sorted({d["bitmapPresent"] for d in ref}),
            "our_bitmap": sorted({d["bitmapPresent"] for d in mine}),
            "extra": [x[len("extra in ours: "):] for x in summary if x.startswith("extra in ours: ")],
            "differ_records": [f"{r[0]} {r[1]}: {r[7]}" for r in rows if r[2] == "yes" and r[3] == "no"],
        }
        def _miss(fs, short, tol, lev):
            return next((d["numberOfMissing"] for d in fs if d["shortName"] == short and d["typeOfLevel"] == tol
                         and d["level"] == lev), None)
        m = [_miss(ref, "t", "heightAboveSea", 305), _miss(mine, "t", "heightAboveSea", 305),
             _miss(ref, "2t", "heightAboveGround", 2), _miss(mine, "2t", "heightAboveGround", 2)]
        if None not in m:
            res["fl_missing"] = m
            noaa_masks, ours_masks = m[0] > m[2], m[1] > m[3]
            res["flight_level_below_ground"] = ("same" if noaa_masks == ours_masks else
                                                "noaa-only" if noaa_masks else "ours-only")
        if nest == "firewxnest" and (n[1] in ("00", "12")) != (o[1] in ("00", "12")):
            res["note"] = "fire-weather grids differ by cycle hour (00/12Z and 06/18Z boxes); compare like with like"
        results[nest] = res
        print(f"{nest}: {res['same']} of {res['records']} with NOAA's text and keys, {res['differ']} differ, "
              f"{res['missing']} missing, {res['renumbered']} renumbered; "
              f"grid {'identical' if res['grid_identical'] else 'differs'}; {res['precision']}")
        if a.out:
            a.out.mkdir(parents=True, exist_ok=True)
            (a.out / f"COMPATIBILITY-{nest}.md").write_text(page(nest, a.hour, res, idxres, head, rows, summary))
    if a.json:
        a.json.write_text(json.dumps(results, indent=1) + "\n")
    if a.out and results:
        (a.out / "COMPATIBILITY.md").write_text(overview(results, a.hour, (a.made_by.strip() + " ") if a.made_by else ""))
    return 0 if results else 1


if __name__ == "__main__":
    sys.exit(main())
